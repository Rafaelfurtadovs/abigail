func TestSystemDNSConfigCache(t *testing.T) {
	var cache cachedSystemDNS
	loaded := 0
	load := func(context.Context) systemDNSConfig {
		loaded++
		return systemDNSConfig{platform: "linux", linuxServers: []string{"127.0.0.53"}}
	}
	start := time.Unix(1_700_000_000, 0)
	var workers sync.WaitGroup
	for i := 0; i < 100; i++ {
		workers.Add(1)
		go func() {
			defer workers.Done()
			cache.get(context.Background(), start.Add(10*time.Second), load)
		}()
	}
	workers.Wait()
	if loaded != 1 {
		t.Fatalf("expected one OS configuration read, got %d", loaded)
	}
	cache.get(context.Background(), start.Add(10*time.Second+systemDNSCacheTTL), load)
	if loaded != 2 {
		t.Fatalf("expected refresh after TTL, got %d reads", loaded)
	}
	canceled, cancel := context.WithCancel(context.Background())
	cancel()
	cache.get(canceled, start.Add(10*time.Second+2*systemDNSCacheTTL), load)
	cache.get(context.Background(), start.Add(10*time.Second+2*systemDNSCacheTTL), load)
	if loaded != 4 {
		t.Fatalf("canceled read must not enter shared cache, got %d reads", loaded)
	}
}

func TestSystemdRouteSelection(t *testing.T) {
	stub := "nameserver 127.0.0.53\n"
	upstream := "nameserver 10.0.0.53\n"
	nss := "hosts: files resolve [!UNAVAIL=return] dns\n"
	if systemdRouteHidden(stub, "/run/systemd/resolve/stub-resolv.conf", nss) {
		t.Fatal("local stub should retain systemd's per-link routing")
	}
	if !systemdRouteHidden(upstream, "/run/systemd/resolve/resolv.conf", nss) {
		t.Fatal("aggregated upstream file loses per-link routing")
	}
	if !systemdRouteHidden(upstream, "", nss) {
		t.Fatal("nss-resolve with upstream DNS must fall back to system API")
	}
	if systemdRouteHidden(upstream, "", "hosts: files dns\n") {
		t.Fatal("plain resolv.conf should be usable")
	}
}

func TestSelectResolvConfServers(t *testing.T) {
	config := `# generated by systemd-resolved
nameserver 127.0.0.53
nameserver 2001:db8::53
nameserver 127.0.0.53 # duplicate
nameserver invalid-address
search example.test
`
	servers, reason := selectResolvConfServers(config)
	want := []string{"127.0.0.53:53", "[2001:db8::53]:53"}
	if reason != "" || !reflect.DeepEqual(servers, want) {
		t.Fatalf("got servers %v, reason %q; want %v", servers, reason, want)
	}
	servers, reason = selectResolvConfServers("search example.test\n")
	if len(servers) != 0 || reason == "" {
		t.Fatalf("missing nameserver must fall back: %v, %q", servers, reason)
	}
}

const scutilFixture = `DNS configuration

resolver #1
  search domain[0] : example.test
  nameserver[0] : 192.0.2.1
  flags    : Request A records, Request AAAA records
  order    : 200000

resolver #2
  domain   : corp.example.test
  nameserver[0] : 10.0.0.53
  flags    : Supplemental, Request A records
  order    : 101200

resolver #3
  domain   : deep.corp.example.test
  nameserver[0] : 10.0.0.54
  flags    : Supplemental, Request A records
  order    : 101100

DNS configuration (for scoped queries)

resolver #1
  nameserver[0] : 192.0.2.1
  if_index : 13 (en0)
  flags    : Scoped, Request A records
  order    : 200000
`

func TestSelectMacDNSServersLongestSuffix(t *testing.T) {
	cases := []struct {
		name string
		want string
	}{
		{"www.example.test", "192.0.2.1:53"},
		{"service.corp.example.test", "10.0.0.53:53"},
		{"app.deep.corp.example.test", "10.0.0.54:53"},
		{"notcorp.example.test", "192.0.2.1:53"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			servers, reason := selectMacDNSServers(tc.name, scutilFixture)
			if reason != "" || len(servers) != 1 || servers[0] != tc.want {
				t.Fatalf("got %v, reason %q; want %q", servers, reason, tc.want)
			}
		})
	}
}

func TestSelectMacDNSServersScopedRouteFallsBack(t *testing.T) {
	config := scutilFixture + `
resolver #2
  domain : secret.example.test
  nameserver[0] : 10.3.3.3
  flags : Scoped, Request A records
  order : 100000
`
	servers, reason := selectMacDNSServers("host.secret.example.test", config)
	if len(servers) != 0 || !strings.Contains(reason, "interface-scoped") {
		t.Fatalf("scoped route must fall back: %v, %q", servers, reason)
	}
}

func TestSelectMacDNSServersAmbiguousRouteFallsBack(t *testing.T) {
	config := `DNS configuration
resolver #1
  domain : corp.example.test
  nameserver[0] : 10.0.0.1
  order : 100000
resolver #2
  domain : corp.example.test
  nameserver[0] : 10.0.0.2
  order : 100000
`
	servers, reason := selectMacDNSServers("app.corp.example.test", config)
	if len(servers) != 0 || !strings.Contains(reason, "conflicting") {
		t.Fatalf("ambiguous route must fall back: %v, %q", servers, reason)
	}
}
